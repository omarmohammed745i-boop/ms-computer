// =====================================
// GET CURRENT LANGUAGE
// =====================================
function getCurrentLanguage() {
    return localStorage.getItem('language') || 'en';
}

// =====================================
// TRANSLATE FUNCTION
// =====================================
function t(key) {
    const lang = getCurrentLanguage();
    if (dictionary[lang] && dictionary[lang][key]) {
        return dictionary[lang][key];
    }
    if (dictionary.en && dictionary.en[key]) {
        return dictionary.en[key];
    }
    return key;
}

// =====================================
// SET LANGUAGE
// =====================================
function setLanguage(lang) {
    if (!dictionary[lang]) return;
    localStorage.setItem('language', lang);
    
    if (lang === 'ar') {
        document.dir = 'rtl';
        document.documentElement.lang = 'ar';
        document.body.classList.add('rtl');
    } else {
        document.dir = 'ltr';
        document.documentElement.lang = lang;
        document.body.classList.remove('rtl');
    }
    
    translatePage();
    updateLanguageButton();
    document.dispatchEvent(new Event('languageChanged'));
    console.log('🌐 Language set to:', lang);
}

// =====================================
// TRANSLATE PAGE
// =====================================
function translatePage() {
    console.log('🔄 Translating page to:', getCurrentLanguage());
    const elements = document.querySelectorAll('[data-lang]');
    
    elements.forEach(el => {
        const key = el.dataset.lang;
        const translation = t(key);
        if (translation !== key) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                if (el.placeholder !== undefined) {
                    el.placeholder = translation;
                }
            } else if (el.tagName === 'SELECT') {
                el.querySelectorAll('option[data-lang]').forEach(option => {
                    const optionKey = option.dataset.lang;
                    const optionTranslation = t(optionKey);
                    if (optionTranslation !== optionKey) {
                        option.textContent = optionTranslation;
                    }
                });
            } else {
                el.textContent = translation;
            }
        }
    });
}

// =====================================
// UPDATE LANGUAGE BUTTON
// =====================================
function updateLanguageButton() {
    const currentLangEl = document.getElementById('current-language');
    if (currentLangEl) {
        const langNames = {
            en: 'English',
            ar: 'العربية',
            fr: 'Français',
            de: 'Deutsch',
            es: 'Español',
            it: 'Italiano',
            tr: 'Türkçe',
            ru: 'Русский',
            zh: '中文',
            ja: '日本語'
        };
        currentLangEl.textContent = langNames[getCurrentLanguage()] || getCurrentLanguage().toUpperCase();
    }
}

// =====================================
// LANGUAGE DROPDOWN
// =====================================
document.addEventListener('DOMContentLoaded', function() {
    console.log('🌐 DOM Loaded - Initializing Language System');
    
    const langBtn = document.getElementById('language-btn');
    const langDropdown = document.getElementById('language-dropdown');

    if (langBtn && langDropdown) {
        langBtn.addEventListener('click', function(e) {
            e.stopPropagation();
            langDropdown.classList.toggle('show');
        });

        const langItems = langDropdown.querySelectorAll('div');
        
        langItems.forEach(item => {
            item.addEventListener('click', function() {
                const lang = this.dataset.lang;
                const langName = this.textContent.trim();
                setLanguage(lang);
                langDropdown.classList.remove('show');
                if (typeof showToast === 'function') {
                    showToast(`🌐 Language changed to ${langName}`);
                }
            });
        });

        document.addEventListener('click', function(e) {
            if (!langBtn.contains(e.target) && !langDropdown.contains(e.target)) {
                langDropdown.classList.remove('show');
            }
        });
    }

    const savedLang = localStorage.getItem('language') || 'en';
    setLanguage(savedLang);
});

console.log('✅ Language System Ready');